-- ให้ระบบนำเลขที่ว่างอยู่ (จากการลบเอกสาร) กลับมาใช้ใหม่ก่อนออกเลขใหม่ท้ายแถว
-- FillGap = 1 : ออกเลขว่างตัวแรกของรอบ เช่น มี 1,3,4 → เอกสารถัดไปได้เลข 2
-- FillGap = 0 : นับต่อจากเลขสูงสุดเสมอ เช่น มี 1,3,4 → เอกสารถัดไปได้เลข 5
ALTER TABLE doc_running
  ADD COLUMN FillGap TINYINT(1) NOT NULL DEFAULT 1
  COMMENT 'นำเลขที่ว่างจากการลบกลับมาใช้ใหม่' AFTER StartSeq;
